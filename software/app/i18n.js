export function makeT(getLang) {
  return (key, vars) => {
    const lang = getLang();
    let s = (T[lang] && T[lang][key]) ?? T.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  };
}
