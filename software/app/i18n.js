export function makeT(getLang) {
  return (key, vars) => {
    const L = getLang();
    let s = (STR[L] && STR[L][key] !== undefined) ? STR[L][key] : (STR.en[key] !== undefined ? STR.en[key] : key);
    if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
    return s;
  };
}
