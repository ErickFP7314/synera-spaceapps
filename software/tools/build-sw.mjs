// Writes software/app/sw.js: a service worker that precaches the whole app, its engine, data, face
// models, fonts and voice clips, so Galley opens and runs with NO network after the first visit
// (station Wi-Fi drops, Mars has no internet at all). Run after changing any app file:
//   node tools/build-sw.mjs
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..", "app");
const ROOT = join(HERE, "..", "..");
const walk = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const skip = /(^|\/)(README\.md|serve\.mjs|sw\.js|\.gitignore|LICENSE(\.txt)?|manifest\.json)$/;
const appFiles = walk(APP).filter((p) => !skip.test(relative(APP, p)));
const data = ["contracts/medical-ranges-config.json", "contracts/telemetry-payload.schema.json", "data/synthetic/galley-14day-scenarios.json",
  "data/reference/environments.json", "data/reference/rules.json", "data/reference/indicator-explanations.json", "data/reference/radiation.json",
  "data/nasa/donki/donki-sep-demo.json", "data/nasa/osdr/inspiration4-crew-labs.json"].map((p) => join(ROOT, p));
const all = [...appFiles, ...data];
const hash = createHash("sha256");
for (const f of all) hash.update(readFileSync(f));
const version = hash.digest("hex").slice(0, 12);
const urls = ["./", ...appFiles.map((p) => "./" + relative(APP, p)), ...data.map((p) => "../../" + relative(ROOT, p))];
const bytes = all.reduce((s, f) => s + statSync(f).size, 0);
writeFileSync(join(APP, "sw.js"), `// GENERATED by software/tools/build-sw.mjs — do not edit by hand.
// Galley offline cache: ${urls.length} files, ${(bytes / 1048576).toFixed(1)} MB. Cache-first, refreshed in the background.
const CACHE = "galley-${version}";
const URLS = ${JSON.stringify(urls, null, 0)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("galley-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async (c) => {
    const hit = await c.match(req, { ignoreSearch: req.mode === "navigate" });
    const net = fetch(req).then((res) => { if (res.ok) c.put(req, res.clone()); return res; }).catch(() => null);
    if (hit) { e.waitUntil(net); return hit; }
    return (await net) || (req.mode === "navigate" ? c.match("./") : Response.error());
  }));
});
self.addEventListener("message", (e) => {
  if (e.data === "galley-status") caches.open(CACHE).then((c) => c.keys()).then((k) => e.source.postMessage({ type: "galley-status", cached: k.length, total: URLS.length, version: CACHE }));
});
`);
console.log("sw.js:", urls.length, "files,", (bytes / 1048576).toFixed(1), "MB, cache", version);
